FONTS_CSS_PATH = frappe.get_app_path("newsletter", "public", "css", "fonts.css")


def _write_fonts_css():
	"""Write public/css/fonts.css with one @font-face per bundled face.

	The rules live in a separate stylesheet rather than inline in the print
	format on purpose: Frappe's PDF pipeline only absolutises `url()` when it
	directly follows a colon, so an inline `src: local(..), url(..)` stays
	relative and wkhtmltopdf fails with ProtocolUnknownError. A <link href>
	IS absolutised for the PDF (and stays relative for the browser), and the
	font url()s inside the file resolve relative to the stylesheet itself in
	both renderers.
	"""
	import os

	rules = ["/* Generated by newsletter.setup_print_format - do not edit by hand. */"]
	for family, faces in BUNDLED_FONTS.items():
		for filename, weight, style in faces:
			rules.append(
				"@font-face { font-family: '%s'; font-weight: %d; font-style: %s; "
				"src: local('%s'), url('../fonts/%s') format('truetype'); }"
				% (family, weight, style, family, filename)
			)
	os.makedirs(os.path.dirname(FONTS_CSS_PATH), exist_ok=True)
	with open(FONTS_CSS_PATH, "w") as f:
		f.write("\n".join(rules) + "\n")


