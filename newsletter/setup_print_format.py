def create_print_format():
	if frappe.db.exists("Print Format", PRINT_FORMAT_NAME):
		pf = frappe.get_doc("Print Format", PRINT_FORMAT_NAME)
	else:
		pf = frappe.new_doc("Print Format")
		pf.name = PRINT_FORMAT_NAME
		pf.doc_type = "Newsletter Issue"
		pf.module = "Newsletter"

	pf.custom_format = 1
	pf.print_format_type = "Jinja"
	pf.standard = "No"
	pf.disabled = 0
	pf.html = _render_html()
	pf.page_size = "A4"
	pf.margin_top = 0
	pf.margin_bottom = 0
	pf.margin_left = 0
	pf.margin_right = 0
	pf.align_labels_right = 0
	pf.show_section_headings = 0
	pf.line_breaks = 0
	pf.font_size = 12
	pf.default_print_language = "en"

	if pf.is_new():
		pf.insert(ignore_permissions=True)
	else:
		pf.save(ignore_permissions=True)

	# Make it the default print format for Newsletter Issue.
	filters = {"doc_type": "Newsletter Issue", "property": "default_print_format"}
	if frappe.db.exists("Property Setter", filters):
		ps = frappe.get_doc("Property Setter", filters)
	else:
		ps = frappe.new_doc("Property Setter")
	ps.doctype_or_field = "DocType"
	ps.doc_type = "Newsletter Issue"
